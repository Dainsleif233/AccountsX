package top.syshub.accountsx.common.accounts.model;

/**
 * 「现有令牌还能不能直接用」的三种结论（B4）。
 *
 * <p><b>为什么不是布尔：</b>「确定无效」和「问不出来」要分开处理。确定无效时刷新是唯一出路；
 * 问不出来（网络抖动、网关超时、服务端 5xx / 429）时令牌很可能仍然是好的——此时刷新会当场
 * 轮换令牌，把另一个实例刚换好的凭据作废，一次网络故障就被升级成账号互踢。所以第三种结论
 * 存在，调用方见到它应当<b>放弃本轮</b>，什么都不做。</p>
 */
public enum TokenReuse {
    /** 确认可用：跳过刷新。 */
    YES,
    /** 确认不可用（服务端明确否认）：刷新。 */
    NO,
    /** 问不出来（网络失败 / 服务端故障）：本轮不要动令牌。 */
    UNKNOWN
}
